args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==2)
source_root <- normalizePath(args[1])
out <- args[2]; dir.create(out,recursive=TRUE,showWarnings=FALSE)
suppressPackageStartupMessages({library(rms);library(pROC);library(dplyr)})
set.seed(20261014)
d <- readRDS(file.path(source_root,'02_clean_data/SEER_T1T2_colon_LNM_final_analysis_cohort.rds'))
stopifnot(nrow(d)==14498,sum(d$lnm_num)==2210,!anyDuplicated(d$patient_id))
d <- as.data.frame(d)
d$site_model<-d$site_group; d$histology_model<-d$histology_group; d$grade_model<-d$grade_group
stopifnot(!anyNA(d[,c('age','site_model','histology_model','grade_model','tumor_size_mm','t_stage','lnm_num')]))
train<-d[d$year_dx<=2021,];test<-d[d$year_dx==2022,]
stopifnot(nrow(train)==11490,nrow(test)==3008,sum(train$lnm_num)==1756,sum(test$lnm_num)==454)
dd<-datadist(train); options(datadist='dd')
f<-lnm_num~rcs(age,c(46,62,72,86))+site_model+histology_model+grade_model+rcs(tumor_size_mm,c(4,20,33,65))+t_stage
m<-lrm(f,data=train,x=TRUE,y=TRUE)
saved<-readRDS(file.path(source_root,'08_models/Primary_race_free_RCS_model_tumor_size_le150.rds'))
delta<-max(abs(coef(m)-coef(saved)))
stopifnot(delta<1e-7)
prob<-function(fit,new)as.numeric(predict(fit,newdata=new,type='fitted'))
evaluate<-function(y,p,label){
 lp<-qlogis(p); roc<-pROC::roc(y,p,quiet=TRUE,direction='<');ci<-as.numeric(ci.auc(roc,method='delong'))
 a<-glm(y~1,offset=lp,family=binomial());s<-glm(y~lp,family=binomial())
 aci<-coef(a)[1]+c(-1,1)*qnorm(.975)*sqrt(vcov(a)[1,1]);sci<-coef(s)[2]+c(-1,1)*qnorm(.975)*sqrt(vcov(s)[2,2])
 b<-mean((y-p)^2);null<-mean(y)*(1-mean(y))
 data.frame(Analysis=label,N=length(y),Events=sum(y),Event_rate=mean(y),AUC=as.numeric(auc(roc)),AUC_lower=ci[1],AUC_upper=ci[3],Brier=b,Null_Brier=null,Scaled_Brier=1-b/null,Calibration_intercept=coef(a)[1],Intercept_lower=aci[1],Intercept_upper=aci[2],Calibration_slope=coef(s)[2],Slope_lower=sci[1],Slope_upper=sci[2],row.names=NULL)
}
write<-function(x,name)write.csv(x,file.path(out,name),row.names=FALSE)
write(data.frame(Check=c('Cohort size','Events','Duplicate patient IDs','Positive nodes greater than examined','Primary coefficient max absolute difference'),Value=c(nrow(d),sum(d$lnm_num),sum(duplicated(d$patient_id)),sum(d$nodes_positive>d$nodes_examined),delta)),'reproduction_checks.csv')
p<-prob(m,test);primary<-evaluate(test$lnm_num,p,'Primary RCS 2018-2021 to 2022')
write(primary,'primary_2022.csv')
subgroups<-bind_rows(lapply(c('T1','T2'),function(st){i<-test$t_stage==st;evaluate(test$lnm_num[i],p[i],st)}));write(subgroups,'subgroup_2022.csv')
linear<-lrm(lnm_num~age+site_model+histology_model+grade_model+tumor_size_mm+t_stage,data=train,x=TRUE,y=TRUE)
t_only<-lrm(lnm_num~t_stage,data=train,x=TRUE,y=TRUE)
bench<-bind_rows(evaluate(test$lnm_num,prob(t_only,test),'T stage only'),evaluate(test$lnm_num,prob(linear,test),'Linear clinicopathologic'),evaluate(test$lnm_num,p,'RCS clinicopathologic'))
write(bench,'benchmark_2022.csv')
roc_primary<-pROC::roc(test$lnm_num,p,quiet=TRUE,direction='<')
comparisons<-bind_rows(lapply(list(list('T stage only',t_only),list('Linear clinicopathologic',linear)),function(x){r<-pROC::roc(test$lnm_num,prob(x[[2]],test),quiet=TRUE,direction='<');tt<-pROC::roc.test(roc_primary,r,paired=TRUE,method='delong');data.frame(Comparator=x[[1]],Delta_AUC=as.numeric(auc(roc_primary)-auc(r)),P=tt$p.value)}))
write(comparisons,'paired_auc_comparisons.csv')
rolling<-list();knots<-list()
for(yr in 2019:2022){
 tr<-d[d$year_dx<yr,];te<-d[d$year_dx==yr,];dd<-datadist(tr)
 fit<-lrm(lnm_num~rcs(age,4)+site_model+histology_model+grade_model+rcs(tumor_size_mm,4)+t_stage,data=tr,x=TRUE,y=TRUE)
 perf<-evaluate(te$lnm_num,prob(fit,te),paste0('2018-',yr-1,' to ',yr));perf$Train_N<-nrow(tr);perf$Test_year<-yr
 rolling[[as.character(yr)]]<-perf
 for(v in c('age','tumor_size_mm'))knots[[paste0(yr,v)]]<-data.frame(Test_year=yr,Variable=v,Order=1:4,Knot=fit$Design$parms[[v]])
}
write(bind_rows(rolling),'rolling_training_only_knots.csv');write(bind_rows(knots),'rolling_knots.csv')
dec<-data.frame(y=test$lnm_num,p=p)%>%mutate(decile=ntile(p,10))%>%group_by(decile)%>%summarise(N=n(),Events=sum(y),Predicted=mean(p),Observed=mean(y),.groups='drop')
z<-qnorm(.975);n<-dec$N;v<-dec$Observed
dec$Lower<-(v+z^2/(2*n)-z*sqrt(v*(1-v)/n+z^2/(4*n^2)))/(1+z^2/n)
dec$Upper<-(v+z^2/(2*n)+z*sqrt(v*(1-v)/n+z^2/(4*n^2)))/(1+z^2/n)
write(dec,'calibration_deciles.csv')
boot_brier<-replicate(1000,{i<-sample.int(nrow(test),replace=TRUE);mean((test$lnm_num[i]-p[i])^2)})
write(data.frame(Brier=primary$Brier,Lower=unname(quantile(boot_brier,.025)),Upper=unname(quantile(boot_brier,.975)),Repetitions=1000,Seed=20261014),'brier_bootstrap_ci.csv')
caldata<-data.frame(y=test$lnm_num,p=p)
calfit<-glm(y~splines::ns(p,df=3),data=caldata,family=binomial())
grid<-data.frame(p=seq(min(p),max(p),length.out=200));pred<-predict(calfit,grid,type='link',se.fit=TRUE)
curve<-data.frame(Predicted=grid$p,Observed=plogis(pred$fit),Lower=plogis(pred$fit-1.96*pred$se.fit),Upper=plogis(pred$fit+1.96*pred$se.fit))
write(curve,'calibration_curve.csv')
write(data.frame(FPR=1-roc_primary$specificities,TPR=roc_primary$sensitivities),'roc_curve.csv')
write(d%>%group_by(year_dx,t_stage)%>%summarise(N=n(),Events=sum(lnm_num),Rate=mean(lnm_num),.groups='drop'),'annual_stage_event_rates.csv')
write(d%>%count(surgery_code,name='N'),'surgery_code_counts.csv')
write(data.frame(T_stage=c('T1','T2'),N=sapply(c('T1','T2'),function(x)sum(train$t_stage==x)),Events=sapply(c('T1','T2'),function(x)sum(train$lnm_num[train$t_stage==x]))),'development_stage_events.csv')
